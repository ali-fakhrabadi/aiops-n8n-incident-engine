#!/usr/bin/env bash
# Create the files in ./secrets that docker-compose.yml mounts as Docker secrets.
#
# Idempotent: existing files are never overwritten, so re-running is safe and rotating
# a secret means deleting its file first (and, for database passwords, changing the
# role's password, since PostgreSQL only reads them when the volume is created).
#
# Requirements: bash and openssl.
set -euo pipefail

cd "$(dirname "$0")/.."
readonly DIR=secrets

umask 077
mkdir -p "$DIR"
# The directory keeps other host users out; files inside are 0644 so every container
# user (postgres, redis, node, the API's uid) can read its bind-mounted secret.
chmod 700 "$DIR"

create_random() {
    local file="$DIR/$1"
    if [[ -s "$file" ]]; then
        echo "kept     $file"
        return
    fi
    # printf is a shell builtin: the value never becomes an argument of another process.
    printf '%s' "$(openssl rand -hex 32)" > "$file"
    echo "created  $file"
}

create_random postgres_superuser_password
create_random aiops_owner_db_password
create_random aiops_app_db_password
create_random n8n_db_password
create_random n8n_encryption_key
create_random redis_password
create_random metrics_token

# Redis reads its password from its configuration file, which therefore is a secret too.
redis_conf="$DIR/redis.conf"
if [[ -s "$redis_conf" ]]; then
    echo "kept     $redis_conf"
else
    {
        echo "# Generated by scripts/generate_secrets.sh; contains the password."
        printf 'requirepass %s\n' "$(cat "$DIR/redis_password")"
        echo "dir /data"
        echo "appendonly yes"
        echo "appendfsync everysec"
        # The alert queue must never be evicted to make room: fail writes instead.
        echo "maxmemory 128mb"
        echo "maxmemory-policy noeviction"
    } > "$redis_conf"
    echo "created  $redis_conf"
fi

chmod 644 "$DIR"/*
